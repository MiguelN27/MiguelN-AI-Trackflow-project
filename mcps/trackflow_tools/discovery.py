"""The tool reference, rendered from what `tools/list` actually returns.

`npm run mcp:tools` prints it - the MCP equivalent of `--help` - and
`docs/mcp/TOOLS.md` is this same rendering (`tests/mcps/test_mcp_discovery.py`
fails when the file and the server disagree), so the documentation is the
discovery and cannot drift from it.
"""

import json
from typing import Any

from fastmcp import Client, FastMCP
from mcp.types import Tool

from mcps.trackflow_tools.audit import MemorySink
from mcps.trackflow_tools.errors import ERROR_DESCRIPTIONS
from mcps.trackflow_tools.permissions import SCOPE_DESCRIPTIONS
from mcps.trackflow_tools.server import SERVER_NAME, SERVER_VERSION, build_server
from mcps.trackflow_tools.upstream import IncidentsApi, ReadOnlyInventoryApi, Upstream

# Never called: discovery only lists the tools.
_NOWHERE = "http://127.0.0.1:9"


def discovery_server() -> FastMCP:
    """The real server's tools and descriptions, without settings or services."""
    upstream = Upstream(
        incidents=IncidentsApi(_NOWHERE, timeout=1),
        inventory=ReadOnlyInventoryApi(_NOWHERE, timeout=1, account=None),
    )
    return build_server(upstream, sink=MemorySink(), auth=lambda: None)


async def list_tools(server: FastMCP | None = None) -> list[Tool]:
    async with Client(server or discovery_server()) as client:
        return await client.list_tools()


def as_json(tools: list[Tool]) -> list[dict[str, Any]]:
    return [
        tool.model_dump(
            mode="json",
            by_alias=True,
            exclude_none=True,
            include={
                "name",
                "title",
                "description",
                "inputSchema",
                "outputSchema",
                "annotations",
                "meta",
            },
        )  # fmt: skip
        for tool in tools
    ]


def _type_of(schema: dict[str, Any]) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{value}`" for value in schema["enum"])
    if "anyOf" in schema:
        options = [_type_of(option) for option in schema["anyOf"] if option.get("type") != "null"]
        nullable = any(option.get("type") == "null" for option in schema["anyOf"])
        return " \\| ".join(options) + (" (optional)" if nullable else "")
    kind = schema.get("type", "any")
    if schema.get("format"):
        kind = f"{kind} ({schema['format']})"
    limits = [
        f"{label} {schema[key]}"
        for key, label in (
            ("minLength", "min length"),
            ("maxLength", "max length"),
            ("minimum", "≥"),
            ("maximum", "≤"),
        )
        if key in schema
    ]
    return kind + (f", {', '.join(limits)}" if limits else "")


def _cell(text: str) -> str:
    return text.replace("\n", " ").replace("|", "\\|")


def render_markdown(tools: list[Tool]) -> str:
    lines = [
        "# TrackFlow company tools — MCP tool reference",
        "",
        "<!-- Generated by `npm run mcp:tools -- --write docs/mcp/TOOLS.md` from the",
        "     server's own tools/list. Do not edit by hand: a test compares them. -->",
        "",
        f"Server `{SERVER_NAME}` {SERVER_VERSION}. Transport: Streamable HTTP (stateless). "
        "Every request needs an OAuth bearer token (see `mcp-server.md`).",
        "",
        "## Scopes",
        "",
        "| Scope | Grants |",
        "| --- | --- |",
        *(f"| `{scope.value}` | {text} |" for scope, text in SCOPE_DESCRIPTIONS.items()),
        "",
        "There is no inventory write scope: the inventory is read-only on this server.",
        "",
        "## Tool error codes",
        "",
        "A refused or failed call is a tool result with `isError: true` whose text is JSON "
        '`{"error": "<code>", "message": "..."}`.',
        "",
        "| Code | Meaning |",
        "| --- | --- |",
        *(f"| `{code.value}` | {_cell(text)} |" for code, text in ERROR_DESCRIPTIONS.items()),
        "",
        "## Tools",
    ]
    for tool in tools:
        meta = tool.meta or {}
        annotations = tool.annotations
        hints = (
            ", ".join(
                f"{name}={getattr(annotations, name)}"
                for name in ("readOnlyHint", "destructiveHint", "idempotentHint", "openWorldHint")
                if getattr(annotations, name) is not None
            )
            if annotations
            else "none"
        )
        lines += [
            "",
            f"### `{tool.name}`"
            + (f" — {annotations.title}" if annotations and annotations.title else ""),
            "",
            f"- Required scopes: {', '.join(f'`{s}`' for s in meta.get('required_scopes', []))}",
            f"- Access: {meta.get('access')} on {meta.get('domain')}",
            f"- Annotations: {hints}",
            "",
            tool.description or "",
            "",
            "**Input**",
            "",
            "| Field | Type | Required | Description |",
            "| --- | --- | --- | --- |",
        ]
        properties = tool.inputSchema.get("properties", {})
        required = set(tool.inputSchema.get("required", []))
        for name, schema in properties.items():
            default = (
                f" Default: `{schema['default']}`." if schema.get("default") is not None else ""
            )
            lines.append(
                f"| `{name}` | {_type_of(schema)} | {'yes' if name in required else 'no'} | "
                f"{_cell(schema.get('description', ''))}{default} |"
            )
        lines += [
            "",
            "**Output** (structured content)",
            "",
            "```json",
            json.dumps(tool.outputSchema, indent=2, sort_keys=True),
            "```",
        ]
    return "\n".join(lines) + "\n"
